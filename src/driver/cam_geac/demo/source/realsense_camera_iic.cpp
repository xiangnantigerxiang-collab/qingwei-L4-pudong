// 初始化I2C操作结构体
I2COperations* i2c_ops_create(int bus_num, int dev_addr) {
    I2COperations* ops = (I2COperations*)malloc(sizeof(I2COperations));
    if (ops == NULL) {
        debug_err("Memory allocation failure !!!\n");
        return NULL;
    }
    
    ops->bus_num = bus_num;
    ops->dev_addr = dev_addr;
    ops->fd = -1;
    
    return ops;
}

// 销毁I2C操作结构体（释放内存）
void i2c_ops_destroy(I2COperations* ops) {
    if (ops == NULL) return;
    
    if (ops->fd >= 0) {
        close(ops->fd);
        ops->fd = -1;
    }
    
    free(ops);
}

