int i2c_init(I2COperations* ops) {
    if (ops == NULL) {
        debug_err("The I2C operation structure is empty !!!\n");
        return -1;
    }
    
    // 构建设备文件名 /dev/i2c-X
    char dev_name[32];
    snprintf(dev_name, sizeof(dev_name), "/dev/i2c-%d", ops->bus_num);
    
    // 以读写模式打开I2C设备
    ops->fd = open(dev_name, O_RDWR);
    if (ops->fd < 0) {
        debug_err("Unable to open I2C device: %s", dev_name);
        return -1;
    }
    
    // 设置I2C从设备地址
    if (ioctl(ops->fd, I2C_SLAVE, ops->dev_addr) < 0) {
        debug_err("Unable to set I2C address: 0x%x", ops->dev_addr);
        close(ops->fd);
        ops->fd = -1;
        return -1;
    }
    return 0;
}

// 底层I2C写操作
int i2c_write(I2COperations* ops, const uint8_t* data, int data_len) {
    if (ops == NULL || ops->fd < 0) {
        debug_err("I2C device not initialized !!!\n");
        return -1;
    }
    
    if (data == NULL || data_len <= 0) {
        debug_err("Write data as empty or invalid length !!!\n");
        return -1;
    }
    
    // 构建I2C消息结构体
    struct i2c_msg msg = {
        .addr = (uint16_t)ops->dev_addr,  // 从设备地址
        .flags = 0,                       // 写操作
        .len = (uint16_t)data_len,        // 数据长度
        .buf = (uint8_t*)data             // 数据缓冲区
    };
    
    struct i2c_rdwr_ioctl_data ioctl_data = {
        .msgs = &msg,
        .nmsgs = 1                        // 消息数量
    };
    
    // 执行I2C写操作
    if (ioctl(ops->fd, I2C_RDWR, &ioctl_data) < 0) {
        debug_err("I2C write operation failed !!!\n");
        return -1;
    }
    return 0;
}

// 底层I2C读操作（先写寄存器地址，再读数据）
int i2c_read(I2COperations* ops, const uint8_t* reg_addr, int reg_len, 
             uint8_t* read_data, int read_len) {
    if (ops == NULL || ops->fd < 0) {
        debug_err("I2C device not initialized !!!\n");
        return -1;
    }
    
    if (reg_addr == NULL || reg_len <= 0 || read_data == NULL || read_len <= 0) {
        debug_err("The register address is empty or the read parameter is invalid !!!\n");
        return -1;
    }
    
    // 构建两个消息：1.写寄存器地址 2.读数据
    struct i2c_msg msgs[2] = {
        // 消息1：写寄存器地址
        {
            .addr = (uint16_t)ops->dev_addr,
            .flags = 0,                     // 写操作
            .len = (uint16_t)reg_len,
            .buf = (uint8_t*)reg_addr
        },
        // 消息2：读数据
        {
            .addr = (uint16_t)ops->dev_addr,
            .flags = I2C_M_RD,              // 读操作
            .len = (uint16_t)read_len,
            .buf = read_data
        }
    };
    
    struct i2c_rdwr_ioctl_data ioctl_data = {
        .msgs = msgs,
        .nmsgs = 2                         // 两个消息
    };
    
    // 执行I2C读写操作
    if (ioctl(ops->fd, I2C_RDWR, &ioctl_data) < 0) {
        debug_err("I2C read operation failed !!!\n");
        return -1;
    }
    
    return 0;
}

int write_26_bytes(I2COperations* ops, DataType data_type) {
    // 定义两组寄存器数据
    uint8_t write_data_rgb[] = {
        0x00, 0x49, 0x14, 0x00, 0xab, 0xcd, 0x15, 0x00,
        0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00
    };  //RGBGET
    uint8_t write_data_depth_old[] = {
        0x00, 0x49, 0x14, 0x00, 0xab, 0xcd, 0x15, 0x00,
        0x00, 0x00, 0x19, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00
    };  //GETINTCAL
    uint8_t write_data_depth_new[] = {
        0x00, 0x49, 0x14, 0x00, 0xab, 0xcd, 0x7e, 0x00, 
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 
        0x00, 0x00,
    };  //RECPARAMSGET
    
    
    // 参数合法性校验
    if (data_type != DATA_TYPE_RGB && data_type != DATA_TYPE_DEPTH_OLD && data_type != DATA_TYPE_DEPTH_NEW) {
        debug_err("Invalid DataType parameter !!!");
        return -1;
    }
    
    // 根据参数选择要写入的数据
    const uint8_t* write_data = NULL;
    int data_len = 0;
    if (data_type == DATA_TYPE_RGB) {
        write_data = write_data_rgb;
        data_len = sizeof(write_data_rgb);
    } else if (data_type == DATA_TYPE_DEPTH_OLD) {
        write_data = write_data_depth_old;
        data_len = sizeof(write_data_depth_old);
    }  else if (data_type == DATA_TYPE_DEPTH_NEW) {
        write_data = write_data_depth_new;  // 新版本使用同一组寄存器数据
        data_len = sizeof(write_data_depth_new);
    }
    
    // 执行写入
    return i2c_write(ops, write_data, data_len);
}

// 步骤2：写入4个字节
int write_4_bytes(I2COperations* ops) {
    uint8_t write_data[] = {0x0c, 0x49, 0x00, 0x01};
    return i2c_write(ops, write_data, sizeof(write_data));
}

// 步骤3：循环读取2个字节，直到为0x00 0x00
int loop_read_2_bytes(I2COperations* ops) {
    uint8_t reg_addr[] = {0x04, 0x49};
    uint8_t read_data[2];
    int retry_count = 0;
    
    // 循环读取，最多尝试100次
    while (retry_count < 100) {
        if (i2c_read(ops, reg_addr, sizeof(reg_addr), read_data, sizeof(read_data)) != 0) {       
            usleep(100000);  // 等待100ms
            retry_count++;
            continue;
        }
        
        // 检查是否读到0x00 0x00
        if (read_data[0] == 0x00 && read_data[1] == 0x00) {
            return 0;
        }
        usleep(100000);  // 等待100ms
        retry_count++;
    }
    debug_err("D415-GMSL 0x10 0x0449: Read timeout !!!\n");
    return -1;
}

// 步骤4：读取2个字节并转换为十进制数（调换字节顺序）
int read_2_bytes_and_convert(I2COperations* ops) {
    uint8_t reg_addr[] = {0x08, 0x49};
    uint8_t read_data[2];
    
    if (i2c_read(ops, reg_addr, sizeof(reg_addr), read_data, sizeof(read_data)) != 0) {
        debug_err("D415-GMSL 0x10 0x0849: Read failed !!!\n");
        return -1;
    }
    
    // 调换字节顺序：原[0]是高位 → 改为原[1]是高位，原[0]是低位
    // 例如：0x04 0x01 → 0x0104 = 260
    int decimal_value = (read_data[1] << 8) | read_data[0];
    return decimal_value;
}

// 步骤5：根据步骤4的数值读取指定长度的数据
uint8_t* read_specified_length(I2COperations* ops, int length, int* out_len) {
    if (length <= 0) {
        debug_err("D415-GMSL 0x10 0x0849: Invalid read length !!!\n");
        *out_len = 0;
        return NULL;
    }
    
    uint8_t reg_addr[] = {0x00, 0x49};
    // 分配内存存储读取的数据
    uint8_t* read_data = (uint8_t*)malloc(length * sizeof(uint8_t));
    if (read_data == NULL) {
        debug_err("D415-GMSL 0x10 0x0049: Memory allocation failure !!!\n");
        *out_len = 0;
        return NULL;
    }
    
    if (i2c_read(ops, reg_addr, sizeof(reg_addr), read_data, length) != 0) {
        debug_err("D415-GMSL 0x10 0x0049: Read failed !!!\n");
        free(read_data);
        *out_len = 0;
        return NULL;
    }
    
    *out_len = length;
    return read_data;
}

// 执行所有操作并返回最终结果
uint8_t* execute_all_operations(I2COperations* ops, DataType data_type, int* out_len) {
    int ret;
    int read_length;
    uint8_t* final_data = NULL;
    uint8_t* truncated_data = NULL;  // 截断后的数据
    int truncated_len = 0;
    
    *out_len = 0;

    // 初始化I2C设备
    if (i2c_init(ops) != 0) {
        return NULL;
    }
    
    // 步骤1
    ret = write_26_bytes(ops, data_type);
    if (ret != 0) {
        return NULL;
    }
    
    // 步骤2
    ret = write_4_bytes(ops);
    if (ret != 0) {
        return NULL;
    }
    
    // 步骤3
    ret = loop_read_2_bytes(ops);
    if (ret != 0) {
        return NULL;
    }
    
    // 步骤4
    read_length = read_2_bytes_and_convert(ops);
    if (read_length <= 0) {
        return NULL;
    }

    // 步骤5
    final_data = read_specified_length(ops, read_length, out_len);
    
    if (final_data != NULL && *out_len > 0) {
        
        // 去掉前4个字节
        if (*out_len > 4) {
            truncated_len = *out_len - 4;
            // 分配新内存存储截断后的数据
            truncated_data = (uint8_t*)malloc(truncated_len * sizeof(uint8_t));
            if (truncated_data == NULL) {
                debug_err("Memory allocation failed while truncating data !!!");
                free(final_data);
                *out_len = 0;
                return NULL;
            }
            // 复制从第5个字节开始的数据（索引4）
            memcpy(truncated_data, final_data + 4, truncated_len);
        } else {
            // 数据长度≤4，截断后无数据
            debug_err("The length of the read data is ≤ 4, and there is no data after removing the first 4 bytes !!!");
            truncated_len = 0;
        }
        
        // 释放原完整数据的内存
        free(final_data);
        final_data = NULL;
        
        // 更新输出长度和返回数据
        *out_len = truncated_len;
        return truncated_data;
    }
}




bool set_high_accuracy_mode(I2COperations* ops, DeviceType device_type) {

    uint8_t* final_data = NULL;
    int success_count = 0;
    int ret;
    int read_length;
    const std::vector<std::vector<uint8_t>>* high_accuracy_configs = nullptr;

    // 期望的验证数据
    const uint8_t expected_final_data[] = {0x2b, 0x00, 0x00, 0x00};

    // 初始化I2C设备
    if (i2c_init(ops) != 0) {
        return NULL;
    }

    if(device_type == DEVICE_TYPE_D405) {
        high_accuracy_configs = &d405_high_accuracy_configs;
        debug_info("Setting high accuracy mode for D405... \n");
    } else if (device_type == DEVICE_TYPE_D415) {
        high_accuracy_configs = &d415_high_accuracy_configs;
        debug_info("Setting high accuracy mode for D415... \n");
    } else if (device_type == DEVICE_TYPE_D457) {
        high_accuracy_configs = &d457_high_accuracy_configs;
        debug_info("Setting high accuracy mode for D457... \n");
    } else {
        debug_err("Invalid device type!\\n");
        return false;
    }

        // 遍历13组配置数据
    for (int group = 0; group < high_accuracy_configs->size(); group++) {
        const auto& config_data = (*high_accuracy_configs)[group];
        
        // 写入配置数据
        int write_ret = i2c_write(ops, config_data.data(), config_data.size());
        if (write_ret != 0) {
            debug_err("Failed to write group %d data!\\n", group);
            continue;
        }
        
        // 延迟等待写入完成
        usleep(1000); // 1ms延迟

        // 步骤2
        ret = write_4_bytes(ops);
        if (ret != 0) {
            return NULL;
        }

        // 步骤3
        ret = loop_read_2_bytes(ops);
        if (ret != 0) {
            return NULL;
        }

        // 步骤4
        read_length = read_2_bytes_and_convert(ops);
        if (read_length <= 0) {
            return NULL;
        }
        
        int actual_len = 0;
        // 读取final_data进行验证
        final_data = read_specified_length(ops, read_length, &actual_len);
        
        if (final_data != NULL && actual_len == sizeof(expected_final_data)) {
            // 验证读取的数据是否匹配期望值
            if (memcmp(final_data, expected_final_data, sizeof(expected_final_data)) == 0) {
                success_count++;
                // debug_info("Group %d verification passed. \n", group);
            } else {
                debug_warn("Group %d verification failed. Got: 0x%02x 0x%02x 0x%02x 0x%02x\\n", 
                          group, final_data[0], final_data[1], final_data[2], final_data[3]);
            }
        } else {
            debug_err("Failed to read verification data for group %d! \n", group);
        }
        // 释放原完整数据的内存
        free(final_data);
        final_data = NULL;
    }
    
    // 检查是否所有13组都验证成功
    if (success_count == high_accuracy_configs->size()) {
        // debug_info("High accuracy mode set successfully! All %d groups passed. \n", success_count);
        return 0;
    } else {
        debug_err("High accuracy mode set failed! Only %d groups passed. \n", success_count);
        return -1;
    }

}
